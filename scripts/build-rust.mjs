import fs from "node:fs/promises";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const localCargo = path.join(root, ".cache/rust/cargo");
const localRustup = path.join(root, ".cache/rust/rustup");
const exe = process.platform === "win32" ? ".exe" : "";
const local = await fs.access(path.join(localCargo, `bin/cargo${exe}`)).then(
  () => true,
  () => false,
);
export const rustEnv = local
  ? { ...process.env, CARGO_HOME: localCargo, RUSTUP_HOME: localRustup }
  : process.env;
export const cargo = local ? path.join(localCargo, `bin/cargo${exe}`) : "cargo";

export function runRust(args) {
  const result = spawnSync(cargo, args, {
    cwd: root,
    env: rustEnv,
    stdio: "inherit",
    windowsHide: true,
  });
  if (result.error)
    throw new Error(
      "构建 Rust 引擎需要 Rust 和 wasm32-unknown-unknown；见 docs/RUST-ENGINE.md",
      { cause: result.error },
    );
  if (result.status !== 0)
    throw new Error(`cargo ${args.join(" ")} 失败 (${result.status})`);
}

runRust([
  "build",
  "--locked",
  "--release",
  "--target",
  "wasm32-unknown-unknown",
  "-p",
  "troncut-engine",
]);
const bytes = await fs.readFile(
  path.join(root, "target/wasm32-unknown-unknown/release/troncut_engine.wasm"),
);
// Embedded bytes work in packaged file:// pages without fetch or extra IPC.
const generated = `// Generated by scripts/build-rust.mjs. Do not edit.\nexport const engineBase64 = ${JSON.stringify(bytes.toString("base64"))};\n`;
const destination = path.join(root, "shared/generated/rust-engine.ts");
await fs.mkdir(path.dirname(destination), { recursive: true });
if ((await fs.readFile(destination, "utf8").catch(() => "")) !== generated) {
  await fs.writeFile(destination, generated);
}
console.log(`Rust 时间线引擎：${bytes.length} bytes (release Wasm)`);
