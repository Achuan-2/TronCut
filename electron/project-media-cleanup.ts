import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { randomUUID } from "node:crypto";
import { validateProject, type Asset, type Project } from "../shared/model";

// Removed copies remain readable by undo, redo and recovery. The project
// folder contains only media referenced by its last successful save.
const removedFiles = new Map<string, string>();
let historyDirectory = path.join(
  os.tmpdir(),
  "troncut-media-undo",
  randomUUID(),
);
const fileKey = (file: string) =>
  process.platform === "win32"
    ? path.resolve(file).toLowerCase()
    : path.resolve(file);

export function setProjectMediaHistoryDirectory(directory: string) {
  historyDirectory = path.resolve(directory);
}

export function resolveProjectMediaPath(file: string) {
  return removedFiles.get(fileKey(file)) ?? file;
}

export function resolveProjectMediaAsset(asset: Asset): Asset {
  const file = resolveProjectMediaPath(asset.path);
  return file === asset.path ? asset : { ...asset, path: file };
}

export function restoredProjectMedia(file: string) {
  removedFiles.delete(fileKey(file));
}

function contained(root: string, file: string) {
  const relative = path.relative(root, file);
  return (
    relative !== ".." &&
    !relative.startsWith(`..${path.sep}`) &&
    !path.isAbsolute(relative)
  );
}

function references(project: Project, root: string) {
  return project.assets.flatMap((asset) =>
    [asset.path, asset.cursorPath].flatMap((file) =>
      file ? [fileKey(path.resolve(root, file))] : [],
    ),
  );
}

/** Called only after the new project JSON has been committed successfully. */
export async function cleanupProjectMedia(
  project: Project,
  file: string,
  previous?: Project,
) {
  const root = path.dirname(path.resolve(file));
  const media = path.join(root, "media");
  const stat = await fs.lstat(media).catch((error: NodeJS.ErrnoException) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
  if (!stat?.isDirectory() || stat.isSymbolicLink()) return [];
  const realRoot = await fs.realpath(root);
  const realMedia = await fs.realpath(media);
  if (!contained(realRoot, realMedia)) throw new Error("工程素材目录越界");
  const kept = new Set(references(project, root));
  // Sibling projects can intentionally share this directory. If a project
  // cannot be read, ownership is uncertain and cleanup must leave it alone.
  for (const entry of await fs.readdir(root, { withFileTypes: true })) {
    if (!entry.isFile() || !/\.(troncut|framecraft|json)$/i.test(entry.name))
      continue;
    const sibling = path.join(root, entry.name);
    if (fileKey(sibling) === fileKey(file)) continue;
    let other: Project;
    try {
      other = validateProject(JSON.parse(await fs.readFile(sibling, "utf8")));
    } catch {
      if (/\.(troncut|framecraft)$/i.test(entry.name)) return [];
      continue;
    }
    references(other, root).forEach((file) => kept.add(file));
  }
  const previouslyOwned = new Set(previous ? references(previous, root) : []);
  const removed: string[] = [];
  for (const entry of await fs.readdir(media, { withFileTypes: true })) {
    if (!entry.isFile()) continue;
    const source = path.join(media, entry.name);
    if (kept.has(fileKey(source))) continue;
    // UUID-prefixed legacy files were generated by TronCut. Leave custom
    // files alone unless the previous saved project explicitly owned them.
    if (
      !previouslyOwned.has(fileKey(source)) &&
      !/^[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}-/i.test(entry.name)
    )
      continue;
    const realSource = await fs.realpath(source);
    if (fileKey(path.dirname(realSource)) !== fileKey(realMedia)) continue;
    await fs.mkdir(historyDirectory, { recursive: true });
    const backup = path.resolve(
      historyDirectory,
      `${randomUUID()}-${entry.name}`,
    );
    if (
      !contained(path.resolve(historyDirectory), backup) ||
      !contained(realMedia, realSource)
    )
      throw new Error("工程素材清理路径越界");
    try {
      await fs.rename(source, backup);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "EXDEV") throw error;
      await fs.copyFile(source, backup);
      await fs.unlink(source);
    }
    removedFiles.set(fileKey(source), backup);
    removed.push(source);
  }
  return removed;
}
